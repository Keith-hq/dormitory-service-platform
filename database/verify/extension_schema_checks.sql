-- 8. 检查扩展表外键及其引用目标。
SELECT CHILD_CONSTRAINT.CONSTRAINT_NAME,
       CHILD.TABLE_NAME AS CHILD_TABLE,
       CHILD.COLUMN_NAME AS CHILD_COLUMN,
       PARENT.TABLE_NAME AS PARENT_TABLE,
       PARENT.COLUMN_NAME AS PARENT_COLUMN
FROM USER_CONS_COLUMNS CHILD
JOIN USER_CONSTRAINTS CHILD_CONSTRAINT
  ON CHILD.CONSTRAINT_NAME = CHILD_CONSTRAINT.CONSTRAINT_NAME
 AND CHILD.OWNER = CHILD_CONSTRAINT.OWNER
JOIN USER_CONS_COLUMNS PARENT
  ON CHILD_CONSTRAINT.R_CONSTRAINT_NAME = PARENT.CONSTRAINT_NAME
 AND CHILD_CONSTRAINT.R_OWNER = PARENT.OWNER
 AND CHILD.POSITION = PARENT.POSITION
WHERE CHILD_CONSTRAINT.CONSTRAINT_TYPE = 'R'
  AND CHILD.TABLE_NAME IN (
      'D_FEE_DETAIL', 'D_WALLET_ACCOUNT', 'D_WALLET_LOG',
      'D_FEE_DEDUCTION_ATTEMPT', 'D_CREDIT_ACCOUNT', 'D_CREDIT_LOG',
      'D_SHARED_ITEM', 'D_ITEM_LOAN', 'D_FACILITY', 'D_FACILITY_BOOKING',
      'D_CLEANING_TASK', 'D_REPAIR_MATERIAL', 'D_REPAIR_MATERIAL_USAGE',
      'D_REPAIR_ATTACHMENT', 'D_USER_ACCOUNT', 'D_NOTIFICATION',
      'D_VISITOR_AUTHORIZATION', 'D_AUDIT_EVENT', 'D_ROOM_VOTE',
      'D_ROOM_VOTE_RESPONSE', 'D_CHECKOUT_LOG', 'D_NOTICE_DISPLAY',
      'D_HYGIENE_COMMENT'
  )
ORDER BY CHILD.TABLE_NAME, CHILD_CONSTRAINT.CONSTRAINT_NAME, CHILD.POSITION;

